-- ============================================================
-- 方法一：CTE（WITH ... AS）写法
-- 优点：逻辑清晰，可读性强，像写步骤一样分步执行
-- 适用：MySQL 8.0+，SQL Server，PostgreSQL，Oracle 等
-- ============================================================

WITH 
-- 【临时表1】各城市汇总数据
city_stats AS (
    SELECT 
        us.city,
        COUNT(DISTINCT os.user_id) AS user_cnt,      -- 支付用户数
        COUNT(os.order_id) AS order_cnt,             -- 支付订单数
        ROUND(SUM(os.pay_amount), 2) AS total_pay    -- 支付总金额
    FROM orders os
    LEFT JOIN users us ON os.user_id = us.user_id
    WHERE os.pay_date BETWEEN '2026-11-01' AND '2026-11-11'
    GROUP BY us.city
),

-- 【临时表2】全国整体水平（基于临时表1计算）
overall_stats AS (
    SELECT 
        ROUND(SUM(total_pay) * 1.0 / SUM(order_cnt), 2) AS overall_avg_price,
        ROUND(SUM(order_cnt) * 1.0 / SUM(user_cnt), 2) AS overall_avg_orders_per_user
    FROM city_stats
),

-- 【临时表3】城市排名及衍生指标（基于临时表1计算）
ranked_cities AS (
    SELECT 
        cs.city,
        cs.total_pay AS '支付总金额',
        ROUND(cs.order_cnt * 1.0 / cs.user_cnt, 2) AS '人均订单数',
        ROUND(cs.total_pay * 1.0 / cs.order_cnt, 2) AS '客单价',
        NTILE(10) OVER (ORDER BY cs.total_pay DESC) AS pay_rank_group
    FROM city_stats cs
)

-- 【最终查询】筛选高价值城市
SELECT 
    rc.city AS '城市',
    rc.支付总金额,
    rc.人均订单数,
    rc.客单价
FROM ranked_cities rc, overall_stats os
WHERE rc.pay_rank_group <= 3
  AND rc.人均订单数 > os.overall_avg_orders_per_user
  AND rc.客单价 > os.overall_avg_price
ORDER BY rc.支付总金额 DESC;


-- ============================================================
-- 方法二：传统嵌套子查询写法（纯 SELECT 嵌套）
-- 优点：兼容所有 MySQL 版本（包括 5.x）
-- 缺点：层级多了可读性较差，括号多了容易数错
-- 执行顺序：从最内层 → 最外层
-- ============================================================

SELECT 
    rc.city AS '城市',
    rc.支付总金额,
    rc.人均订单数,
    rc.客单价
FROM (
    -- ============================================================
    -- 第3层：ranked_cities（城市排名及衍生指标）
    -- 基于最内层的 city_stats 计算人均订单数、客单价、排名分桶
    -- ============================================================
    SELECT 
        cs.city,
        cs.total_pay AS '支付总金额',
        ROUND(cs.order_cnt * 1.0 / cs.user_cnt, 2) AS '人均订单数',
        ROUND(cs.total_pay * 1.0 / cs.order_cnt, 2) AS '客单价',
        NTILE(10) OVER (ORDER BY cs.total_pay DESC) AS pay_rank_group
    FROM (
        -- ============================================================
        -- 第1层（最内层）：city_stats（各城市汇总数据）
        -- 按城市分组，统计支付用户数、订单数、总金额
        -- ============================================================
        SELECT 
            us.city,
            COUNT(DISTINCT os.user_id) AS user_cnt,
            COUNT(os.order_id) AS order_cnt,
            ROUND(SUM(os.pay_amount), 2) AS total_pay
        FROM orders os
        LEFT JOIN users us ON os.user_id = us.user_id
        WHERE os.pay_date BETWEEN '2026-11-01' AND '2026-11-11'
        GROUP BY us.city
    ) cs   -- 第1层结束，别名为 cs
) rc,   -- 第3层结束，别名为 rc
-- ============================================================
-- 第2层：overall_stats（全国整体水平）
-- 注意：overall_stats 和第1层 city_stats 是同一层级，
-- 都用逗号连接在 FROM 中，是并列关系，不是包含关系
-- 但因为要放在 rc 的后面，所以写在这里
-- ============================================================
(
    SELECT 
        ROUND(SUM(total_pay) * 1.0 / SUM(order_cnt), 2) AS overall_avg_price,
        ROUND(SUM(order_cnt) * 1.0 / SUM(user_cnt), 2) AS overall_avg_orders_per_user
    FROM (
        -- 这里复用了【第1层】的相同逻辑（各城市汇总）
        -- 注意：这段代码和第1层的 cs 子查询内容是【完全一样】的！
        -- 这就是嵌套子查询最大的缺点：同样一段逻辑要写两遍
        SELECT 
            us.city,
            COUNT(DISTINCT os.user_id) AS user_cnt,
            COUNT(os.order_id) AS order_cnt,
            ROUND(SUM(os.pay_amount), 2) AS total_pay
        FROM orders os
        LEFT JOIN users us ON os.user_id = us.user_id
        WHERE os.pay_date BETWEEN '2026-11-01' AND '2026-11-11'
        GROUP BY us.city
    ) cs2   -- 别名 cs2（为了区分，可以写不同的别名）
) os   -- 第2层结束，别名为 os
WHERE 
    rc.pay_rank_group <= 3   -- 条件1：支付金额排前30%
    AND rc.人均订单数 > os.overall_avg_orders_per_user   -- 条件2：人均订单数 > 全国平均
    AND rc.客单价 > os.overall_avg_price   -- 条件3：客单价 > 全国平均
ORDER BY rc.支付总金额 DESC;