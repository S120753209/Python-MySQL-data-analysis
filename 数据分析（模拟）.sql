（用户表有城市分布，整体平均客单价 = 总支付金额 / 总订单数（全国），整体人均订单数 = 总订单数 / 有支付行为的用户数（全国）
                    SUM(os.pay_amount)/COUNT(os.order_id)            COUNT(os.order_id)/COUNT(DISTINCT os.pay_amount) 单个用户可以有多比订单，需去重，否则比值始终为1
