CREATE TABLE `users`(
	`user_id` int primary key auto_increment comment'用户ID',
    `register_date` date NOT NULL comment'注册日期',
    `user_level` varchar(10) NOT NULL comment'会员等级（普通/白银/黄金/砖石）',
    `city` varchar(20) NOT NULL comment'所在城市'
